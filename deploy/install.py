def plan(ctx, settings):
    spec = SPECS[ctx.release.component]
    lines = [] if _account(ctx) else [f"create the system account {ctx.release.component} (its own group, nologin)"]
    source = settings.get("config_dir") or "Crocodile registration (--url/--callers)"
    lines += [f"{ctx.home}: state/ (the account's), config/ and {CREDENTIALS}/ from {source}"]
    if "index" in settings:
        lines.append(f"{ctx.home / 'snapshots'}: {Path(settings['index']).name} from {settings['index']}")
    if "edge_network" in settings:
        lines.append(f"the container joins the docker network {settings['edge_network']} (must exist)")
    if settings.get("loopback_port"):
        lines.append("its port is published on the host's loopback: 127.0.0.1:18518")
    if spec.admin:
        lines.append(f"{ADMIN_DIR / ('boring-' + spec.admin)} (root only)")
    shown = {k: v for k, v in settings.items() if k not in ("config_dir", "index")}
    lines.append(f"compose.yaml from the release's template ({', '.join(f'{k}={v}' for k, v in shown.items()) or 'no settings'})")
    lines.append("then the first deploy: build the image, start the container, smoke")
    lines.extend(_proposed_inputs(ctx, settings))
    lines.append(_proposed_exposure(ctx, settings))
    if settings.get("url"):
        for target in _registration_plan(ctx, settings):
            lines.append("Crocodile service-add plan: " + json.dumps(target["proposal"], sort_keys=True))
        lines.append("register after typed APPLY; write the secret directly into HOME/credentials")
    elif settings.get("callers"):
        raise Failure("--callers needs --url (the Crocodile registration path)")
    return lines


def _check_config(directory, name, read_text):
    service = Path(directory) / name
    try:
        if not isinstance(json.loads(read_text(service, "utf-8")), dict):
            raise ValueError
    except (OSError, ValueError):
        raise Failure(f"{service}: a {name} (a JSON object) is needed; see the examples") from None


def _admin_json(arguments, *, apply=False, expected_type=dict):
    # The admin owns plan/APPLY. Inherit its terminal prompt/input, capture only
    # its JSON stdout. Never attach captured stdout to an exception or log.
    try:
        reply = root_child([CROCODILE, *arguments], stdout=subprocess.PIPE,
                           stderr=None, stdin=None if apply else subprocess.DEVNULL,
                           text=True, check=False)
    except OSError:
        raise Failure("Crocodile admin could not start; check its installation") from None
    if reply.returncode:
        raise Failure("Crocodile " + arguments[0] + " did not complete; inspect service-list before retrying")
    try:
        data = json.loads(reply.stdout)
    except (TypeError, ValueError):
        raise Failure("Crocodile admin returned invalid JSON; inspect service-list before retrying") from None
    if not isinstance(data, expected_type):
        raise Failure("Crocodile admin returned an invalid JSON shape")
    return data


def _registration_targets(ctx, settings, read_text):
    if not settings.get("config_dir"):
        if ctx.release.component == "boring-mcp-ferry":
            raise Failure("Ferry needs --config-dir for its routing configuration")
        return [dict(name=ctx.release.component.removeprefix("boring-"),
                     relative=Path(CONFIG_NAME), data={}, url=settings["url"], secret="mcp-client-secret")]
    directory = _input_path(settings["config_dir"])
    if ctx.release.component == "boring-mcp-ferry":
        from ferry_config import read
        fronts = read(directory / CONFIG_NAME, read_text=read_text).frontends
        if not fronts:
            raise Failure("--url needs at least one selected Ferry frontend")
        paths = [(front.name, front.service) for front in fronts]
        if len(paths) == 1 and settings["url"].startswith(("http://", "https://")):
            urls = {paths[0][0]: settings["url"]}
        else:
            urls = {}
            for entry in settings["url"].split(","):
                name, separator, value = entry.partition("=")
                if not separator or not name or not value or name in urls:
                    raise Failure("Ferry --url needs distinct NAME=URL entries for every frontend")
                urls[name] = value
            if set(urls) != {name for name, _ in paths}:
                raise Failure("Ferry --url must name exactly " + ", ".join(name for name, _ in paths))
    else:
        name = ctx.release.component.removeprefix("boring-")
        paths, urls = [(name, directory / CONFIG_NAME)], {name: settings["url"]}
    targets = []
    for name, source in paths:
        # Check the original path before resolving it: never hide a link before
        # root_input sees it. Ferry owns selection, the copier owns destination.
        try:
            data = json.loads(read_text(source, "utf-8"))
        except (OSError, ValueError):
            raise Failure(f"{source}: a frontend JSON object is needed") from None
        if not isinstance(data, dict):
            raise Failure(f"{source}: a frontend JSON object is needed")
        try:
            relative = source.resolve().relative_to(directory.resolve())
        except ValueError:
            raise Failure("registered frontend must be inside --config-dir: " + str(source)) from None
        replaced = set(data) & {"mode", "crocodile", "keys", "issuer", "oauth", "pond", "access"}
        if replaced:
            raise Failure("registration owns " + ", ".join(sorted(replaced)) +
                          "; use --url and --callers NAME=ROLE with an authentication-free config-dir")
        secret = "mcp-client-secret" + ("." + name if ctx.release.component == "boring-mcp-ferry" else "")
        if any((directory / CREDENTIALS / item).exists() for item in ("mcp-client-secret", secret)):
            raise Failure("remove the prepared mcp-client-secret; --url and --callers create it directly in HOME/credentials")
        targets.append(dict(name=name, relative=relative, data=data, url=urls[name], secret=secret))
    return targets


def _registration_plan(ctx, settings):
    def read_text(path, encoding):
        with root_input(_input_path(path)) as source:
            return source.read_text(encoding)
    targets = _registration_targets(ctx, settings, read_text)
    inventory = _admin_json(["list", "--json"])
    authority = inventory.get("public_base_url")
    if not isinstance(authority, str) or not authority:
        raise Failure("Crocodile inventory needs public_base_url; update its admin")
    spec = SPECS[ctx.release.component]
    for target in targets:
        arguments = ["service-add", target["name"], "--url", target["url"],
                     "--callers", settings.get("callers", ""),
                     "--roles", ",".join(spec.roles), "--default-role", spec.default_role]
        proposal = _admin_json(arguments)
        if "client_secret" in proposal:
            raise Failure("Crocodile preview unexpectedly returned a credential")
        target.update(authority=authority, proposal=proposal, arguments=arguments)
    return targets


def _register(ctx, settings, account, registration):
    credentials = ctx.home / CREDENTIALS
    # _config just created this under the root-controlled HOME. Claim the
    # directory before giving it write permission; the service cannot race us.
    os.chown(credentials, 0, 0)
    credentials.chmod(0o700)
    for target in registration:
        secret = credentials / target["secret"]
        fd = os.open(secret, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        ctx.changed.append("Crocodile service-add may have changed " + target["name"])
        try:
            added = _admin_json([*target["arguments"], "--apply"], apply=True)
            client_id, value = added.get("client_id"), added.get("client_secret")
            if (not isinstance(client_id, str) or not client_id.startswith("svc_")
                    or not isinstance(value, str) or not value):
                raise Failure("Crocodile credential reply is invalid; inspect service-list before retrying")
            with os.fdopen(fd, "w", encoding="utf-8", closefd=False) as output:
                output.write(value + "\n")
                output.flush()
                os.fsync(fd)
            os.fchmod(fd, 0o400)
        finally:
            os.close(fd)
        os.chown(secret, account.pw_uid, 0)
        destination = ctx.home / "config" / target["relative"]
        data = {**target["data"], "url": target["url"], "mode": "crocodile",
                "crocodile": {"url": target["authority"], "client_id": client_id,
                              "secret_file": os.path.relpath(secret, destination.parent)}}
        parent = destination.parent
        os.chown(parent, 0, 0)
        parent.chmod(0o700)
        temporary = destination.with_name(destination.name + ".register")
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            json.dump(data, output, indent=2)
            output.write("\n")
            output.flush()
            os.fsync(output.fileno())
            os.fchmod(output.fileno(), 0o400)
        os.chown(temporary, account.pw_uid, 0)
        os.replace(temporary, destination)
        parent.chmod(0o500)
        os.chown(parent, account.pw_uid, 0)
        ctx.log("Crocodile service " + target["name"] + " registered; credentials written privately")
    credentials.chmod(0o500)
    os.chown(credentials, account.pw_uid, 0)


def _input_path(path):
    return Path(path).expanduser().absolute()


def _proposed_inputs(ctx, settings):
    """Validate every selected source before effects; return safe plan metadata."""
    lines = []
    if not settings.get("config_dir"):
        if ctx.release.component == "boring-mcp-ferry":
            raise Failure("Ferry needs --config-dir for its routing configuration")
        if not settings.get("url"):
            raise Failure("use --url and --callers for Crocodile mode, or --config-dir for keys/own-issuer mode")
    else:
        directory = _input_path(settings["config_dir"])
        with root_input(directory, directory=True) as source:
            lines.extend(source.describe())

        def read_text(path, encoding):
            with root_input(_input_path(path)) as source:
                lines.extend(source.describe())
                return source.read_text(encoding)

        _check_config(directory, CONFIG_NAME, read_text)
        if ctx.release.component == "boring-mcp-ferry":
            from ferry_config import read
            for frontend in read(directory / CONFIG_NAME, read_text=read_text).frontends:
                _check_config(frontend.service.parent, frontend.service.name, read_text)
        if settings.get("url"):
            _registration_targets(ctx, settings, read_text)
    if "index" in settings:
        with root_input(_input_path(settings["index"])) as source:
            lines.extend(source.describe())
    return list(dict.fromkeys(lines))


def _copy_input(source, target):
    with root_input(_input_path(source)) as checked:
        checked.copy_to(Path(target))
    return target


def _same_file_content(a, b):
    with root_input(_input_path(a)) as source:
        if not b.is_file() or os.fstat(source.fd).st_size != b.stat().st_size:
            return False
        def digest(handle):
            result = hashlib.sha256()
            for block in iter(lambda: handle.read(1 << 20), b""):
                result.update(block)
            return result.digest()
        # Keep large indexes streamed and read the admitted source descriptor.
        with os.fdopen(os.dup(source.fd), "rb") as first, b.open("rb") as second:
            return digest(first) == digest(second)


def _index_copy(ctx, source):
    """Whether the index must be copied into HOME/snapshots/: not when it, or the
    same content under its name, is there already (a reinstall names its source
    again). Another file under that name stops the install before it changes anything."""
    source, target = Path(source), ctx.home / "snapshots" / Path(source).name
    if _same_file_content(source, target):
        return False
    if target.exists():
        raise Failure(f"{target} exists with other content than {source}",
                      "name the one in snapshots/, or move it away first")
    return True


def _index(ctx, source, copy):
    """The index in HOME/snapshots/, read-only; returns its name."""
    snapshots = ctx.home / "snapshots"
    snapshots.mkdir(mode=0o755, exist_ok=True)
    target = snapshots / Path(source).name
    if copy:
        partial = target.with_name(target.name + ".partial")
        partial.unlink(missing_ok=True)  # remove a stale name without following it
        _copy_input(source, partial)
        partial.rename(target)
    target.chmod(0o444)
    return target.name


def _remove_tree(path):
    """rmtree, also of the read-only trees install makes (config/)."""
    if not path.exists():
        return
    for directory in [path, *(p for p in path.rglob("*") if p.is_dir() and not p.is_symlink())]:
        directory.chmod(0o700)
    shutil.rmtree(path)


def _config(ctx, source, account):
    """Create private directories for registration, or copy an explicitly selected
    config-dir and its credentials read-only through the checked input owner."""
    if not source:
        home_fd = os.open(ctx.home, os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC)
        try:
            for name in ("config", CREDENTIALS):
                os.close(_service_directory(home_fd, ctx.home / name, account, 0o500))
        finally:
            os.close(home_fd)
        return
    secrets = Path(source) / CREDENTIALS
    _read_only_copy(ctx, source, "config", account, ignore=lambda folder, names:
                    [CREDENTIALS] if Path(folder) == Path(source) else [])
    if secrets.is_dir():
        _read_only_copy(ctx, secrets, CREDENTIALS, account)
    else:
        (ctx.home / CREDENTIALS).mkdir(mode=0o500, exist_ok=True)
        os.chown(ctx.home / CREDENTIALS, account.pw_uid, 0)


def _read_only_copy(ctx, source, name, account, ignore=None):
    with root_input(_input_path(source), directory=True):
        pass
    target, new = ctx.home / name, ctx.home / f"{name}.new"
    _remove_tree(new)
    # copytree writes file contents before applying source modes. Keep secrets
    # private throughout that copy, and restore the deploy engine's umask.
    mask = os.umask(0o077)
    try:
        # copy2 would restore a broad source mode before our final chmod pass.
        shutil.copytree(source, new, symlinks=False, ignore=ignore, copy_function=_copy_input)
    finally:
        os.umask(mask)
    for path in [new, *new.rglob("*")]:
        os.chown(path, account.pw_uid, 0)
        path.chmod(0o500 if path.is_dir() else 0o400)
    old = ctx.home / f"{name}.old"
    _remove_tree(old)
    if target.exists():
        target.rename(old)
    new.rename(target)
    _remove_tree(old)


def _compose_text(ctx, settings, account):
    text = (ctx.release.directory / "install" / "compose.yaml").read_text()
    values = {"@UID@": str(account.pw_uid), "@GID@": str(account.pw_gid),
              "@EDGE_NETWORK@": settings.get("edge_network", ""),
              "@INDEX@": Path(settings.get("index", "")).name}
    for key, value in values.items():
        text = text.replace(key, value)
    lines = []
    for line in text.splitlines():
        marker = next((m for m in FLAG_MARKERS if m in line), None)
        if marker is not None:
            if not settings.get(FLAG_MARKERS[marker]):
                continue
            line = line.split("#", 1)[0].rstrip()
        lines.append(line)
    text = "\n".join(lines) + "\n"
    if "@FERRY_LISTENERS@" in text:
        text = text.replace("@FERRY_LISTENERS@", _ferry_listeners(ctx, settings, text))
    return text


def _render_template(ctx, text):
    from steps import managed_service, MARKER_IMAGE
    with tempfile.TemporaryDirectory(prefix="boring-service-plan-") as folder:
        path = Path(folder) / "compose.yaml"
        path.write_text(text)
        reply = ctx.run("docker", "compose", "--project-directory", str(ctx.home),
                        "-f", str(path), "config", "--format", "json", env={"BORING_IMAGE": MARKER_IMAGE})
        return managed_service(json.loads(reply.stdout))


def _ferry_listeners(ctx, settings, text):
    """Ferry owns frontend selection; normalized Compose owns addresses/ports."""
    from ferry_config import read
    _, service = _render_template(ctx, text.replace("@FERRY_LISTENERS@", "{}"))
    bind = (service.get("networks") or {}).get("default", {}).get("ipv4_address")
    ports = sorted({p["target"] for p in service.get("ports", []) if p.get("protocol", "tcp") == "tcp"})
    if not bind or not ports:
        raise Failure("Ferry Compose needs a fixed default-network address and published TCP target ports")
    directory = _input_path(settings["config_dir"])
    def read_text(path, encoding):
        with root_input(_input_path(path)) as source:
            return source.read_text(encoding)
    fronts = read(directory / CONFIG_NAME, read_text=read_text).frontends
    if len(fronts) > len(ports):
        raise Failure("Ferry Compose has fewer target ports than selected frontends")
    listeners = {}
    for front, port in zip(fronts, ports):
        with root_input(_input_path(front.service)):
            try:
                relative = front.service.resolve().relative_to(directory.resolve())
            except ValueError:
                raise Failure("Ferry frontend must be inside --config-dir: " + str(front.service)) from None
        listeners[str(Path("/run/config") / relative)] = {"bind":bind, "port":port}
    # This value sits inside a YAML single-quoted scalar, then Compose
    # interpolates it. Preserve file names across both parsers.
    return json.dumps(listeners, sort_keys=True).replace("\'", "\'\'").replace("$", r"\u0024")


def _proposed_exposure(ctx, settings):
    from steps import exposure
    account = _account(ctx) or SimpleNamespace(pw_uid=0, pw_gid=0)
    name, service = _render_template(ctx, _compose_text(ctx, settings, account))
    return name + " exposure: " + exposure(service)


def _compose(ctx, settings, account):
    temporary = ctx.home / "compose.yaml.new"
    temporary.write_text(_compose_text(ctx, settings, account))
    temporary.chmod(0o644)
    os.replace(temporary, ctx.home / "compose.yaml")


def ready(ctx, settings):
    """What the settings name must be there before anything changes."""
    _proposed_inputs(ctx, settings)
    _proposed_exposure(ctx, settings)
    if "edge_network" in settings and ctx.run("docker", "network", "inspect", settings["edge_network"],
                                               check=False).returncode != 0:
        raise Failure(f"no docker network {settings['edge_network']}", "the edge's network must exist first")
    if "index" in settings:
        _index_copy(ctx, settings["index"])


def install(ctx, settings):
    _proposed_inputs(ctx, settings)  # recheck all sources before any host change
    _proposed_exposure(ctx, settings)
    component, home = ctx.release.component, ctx.home
    spec = SPECS[component]
    registration = _registration_plan(ctx, settings) if settings.get("url") else None
    if settings.get("callers") and registration is None:
        raise Failure("--callers needs --url (the Crocodile registration path)")
    copy_index = _index_copy(ctx, settings["index"]) if "index" in settings else False
    if _account(ctx) is None:
        ctx.run("useradd", "--system", "--user-group", "--no-create-home", "--home-dir", "/nonexistent",
                "--shell", "/usr/sbin/nologin", "--comment", f"{component} service account", component)
        ctx.log(f"created the account {component}")
    account = _account(ctx)
    home.mkdir(mode=0o755, parents=True, exist_ok=True)
    home_fd = os.open(home, os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC)  # root's: it may be a symlink
    try:
        state_fd = _service_directory(home_fd, home / "state", account, spec.state_mode)
        try:
            os.close(_service_directory(state_fd, home / "state" / "oauth", account, 0o700))
        finally:
            os.close(state_fd)
    finally:
        os.close(home_fd)
    _config(ctx, settings.get("config_dir"), account)
    if registration is not None:
        _register(ctx, settings, account, registration)
    if "index" in settings:
        settings = {**settings, "index": _index(ctx, settings["index"], copy_index)}
    ctx.log(f"{home}: state/, config/ and {CREDENTIALS}/ ready" + (", the index in snapshots/" if "index" in settings else ""))
    if spec.admin:
        target = ADMIN_DIR / f"boring-{spec.admin}"
        text = (ctx.release.directory / "install" / spec.admin).read_text().replace("@HOME@", str(home))
        temporary = target.with_name(target.name + ".new")
        temporary.write_text(text)
        temporary.chmod(0o750)
        os.replace(temporary, target)
        ctx.log(f"installed {target}")
    _compose(ctx, settings, account)
    ctx.log(f"wrote {home / 'compose.yaml'} (yours from now on)")


