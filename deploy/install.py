def _installed_frontends(ctx):
    """Read through the installed image's parser, including a stopped stack."""
    from steps import _service, _config_inside, _in_candidate, _without_fixed_addresses, frontend_metadata
    name, service = _service(ctx)
    inside = _config_inside(ctx, name, service)
    if inside is None:
        raise Failure("cannot identify installed service config; keep the account and grants")
    code = inspect.getsource(frontend_metadata) + """
import json, sys
print(json.dumps(frontend_metadata(sys.argv[1])))
"""
    reply = _in_candidate(ctx, name, code, inside,
                          override=_without_fixed_addresses(name, service), read_sealed=True)
    try:
        return json.loads(reply.stdout)
    except (TypeError, ValueError):
        raise Failure("installed service metadata is invalid; keep the account and grants") from None


def _unregistration_plan(ctx):
    fronts = _installed_frontends(ctx)
    if not isinstance(fronts, dict):
        raise Failure("installed service metadata must be an object")
    admitted = [info for info in fronts.values() if info["client_id"] is not None]
    if not admitted:
        return []
    authority = _admin_json(["list", "--json"]).get("public_base_url")
    if any(info["authority_url"] != authority for info in admitted):
        raise Failure("installed service uses another Crocodile; remove its grants at that authority before uninstall")
    records = _admin_json(["service-list"], expected_type=list)
    if any(not isinstance(record, dict) or not isinstance(record.get("client_id"), str)
           or not isinstance(record.get("name"), str) for record in records):
        raise Failure("Crocodile service-list returned invalid identities")
    plans = {}
    for info in admitted:
        matched = [record for record in records if record["client_id"] == info["client_id"]]
        if not matched:
            continue  # already removed; a same-name replacement is left alone
        if len(matched) != 1:
            raise Failure("Crocodile service-list has ambiguous client identity")
        record = matched[0]
        arguments = ["service-remove", record["name"], "--expected-definition", json.dumps(record, sort_keys=True)]
        proposal = _admin_json(arguments)
        ctx.log("Crocodile service-remove plan: " + json.dumps(proposal, sort_keys=True))
        plans[record["client_id"]] = arguments
    return list(plans.values())


def uninstall(ctx, delete_data):
    component, home = ctx.release.component, ctx.home
    spec = SPECS[component]
    compose = home / "compose.yaml"
    removals = _unregistration_plan(ctx) if delete_data else []
    Docker().compose(ctx, "down", image="uninstall")
    ctx.log("container and network removed")
    for arguments in removals:
        ctx.changed.append("Crocodile service-remove may have changed " + arguments[1])
        _admin_json([*arguments, "--apply"], apply=True)
    account = _account(ctx)
    if delete_data and account is not None:
        kept = [home / "state", home / "config", home / CREDENTIALS] + [
            home / f"{name}.{end}" for name in ("config", CREDENTIALS) for end in ("new", "old")
            if (home / f"{name}.{end}").exists()]
        seal(ctx, kept, account.pw_uid)  # raises: the account stays, for a rerun
        ctx.run("userdel", component)
        ctx.log(f"account {component} removed; what it owned is sealed (root's, 0700)")
    # Keep the installed reader and image pointer until sealing AND account
    # removal finish: either can fail and leave this uninstall to retry.
    image = ctx.release.details["image"]
    for tag in ctx.run("docker", "image", "ls", image, "--format", "{{.Tag}}", check=False).stdout.split():
        if tag != "<none>":
            ctx.run("docker", "image", "rm", f"{image}:{tag}", check=False)
    for name in ("release", "release.previous", "release.new"):
        shutil.rmtree(home / name, ignore_errors=True)
    (home / IMAGE_ENV).unlink(missing_ok=True)
    migrate_image_env(home / ".env")
    ctx.log("images, release directories and boring-image.env removed; operator .env kept")
    if spec.admin:
        (ADMIN_DIR / f"boring-{spec.admin}").unlink(missing_ok=True)
    target = home / "compose.yaml.uninstalled"
    if target.exists():
        target = home / f"compose.yaml.uninstalled-{datetime.datetime.now():%Y%m%dT%H%M%S}"
    compose.rename(target)  # last: until here look says installed, and a rerun finishes
    return [str(p) for p in sorted(home.iterdir()) if p.name not in {"DEPLOYED", "COMPONENT"}]
